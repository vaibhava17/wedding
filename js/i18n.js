let current = 'hi';
const listeners = new Set();

export const t = (key, lang = current) => STRINGS[lang][key] ?? STRINGS.hi[key] ?? key;
export const lang = () => current;
export const onLang = (fn) => listeners.add(fn);

export function setLang(next) {
  current = next === 'en' ? 'en' : 'hi';
  const root = document.documentElement;
  root.lang = current;
  root.dataset.lang = current;
  document.title = t('meta.title');
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const v = t(el.dataset.i18n);
    if (el.dataset.i18nHtml !== undefined) el.innerHTML = v; else el.textContent = v;
    el.toggleAttribute('data-empty', v === '');
  });
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':');
      el.setAttribute(attr, t(key));
    }
  });
  try { localStorage.setItem('wedding-lang', current); } catch { /* private mode */ }
  listeners.forEach((fn) => fn(current));
}

export function initialLang() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q === 'en' || q === 'hi') return q;
  try { const s = localStorage.getItem('wedding-lang'); if (s) return s; } catch { /* ignore */ }
  return 'hi';
}
